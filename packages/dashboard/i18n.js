/**
 * t('key') o t('key', { var: valor }) — reemplaza {{var}} en el string.
 * Si falta la clave en el idioma activo, cae a español antes que romper
 * la página (mismo principio que default_locale en la extensión).
 */
export function t(key, vars) {
  let str = STRINGS[LANG]?.[key] ?? STRINGS.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split('{{' + k + '}}').join(v);
    }
  }
  return str;
}

/** Aplica t() a todo elemento con data-i18n en el DOM (texto plano) o
 * data-i18n-html (permite <br>/<em>/etc. dentro del string traducido). */
export function applyStaticTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
  });
}
